"""Explicit input contracts for all 19 engines (AGENTS.md Axiom 2 #2/#3, spec 13.10 'error handling').

Every engine is run against the adversarial probes generated by ``BaseEngine.contract_probes()``
(empty, whitespace, random bytes, {}, [], malformed JSON/XML, nesting bombs one level beyond the limit,
unrelated JSON) — both through the runner and through the HTTP API. None may produce a verdict:
status FAILED, exactly one UNKNOWN input-validation finding, no exception text, never HTTP 500.
"""

